from abc import ABC, abstractmethod
from collections.abc import Mapping, Sequence
from typing import Any

from .types import Action, Observation, StepResult


class Agent(ABC):
    @abstractmethod
    def reset(self): ...
    @abstractmethod
    def act(self, observation: Observation) -> Action: ...
    @abstractmethod
    def get_state(self) -> Sequence[float]: ...
    @abstractmethod
    def set_state(self, state: Sequence[float]): ...
    @abstractmethod
    def parameters(self) -> Sequence[float]: ...
    @abstractmethod
    def load_parameters(self, parameters: Sequence[float]): ...
    @abstractmethod
    def metadata(self) -> Mapping[str, Any]: ...

class Environment(ABC):
    @abstractmethod
    def reset(self, seed: int | None = None) -> Observation: ...
    @abstractmethod
    def step(self, action: Action) -> StepResult: ...
    @abstractmethod
    def observation(self) -> Observation: ...
    @abstractmethod
    def terminated(self) -> bool: ...
    @abstractmethod
    def truncated(self) -> bool: ...
    @abstractmethod
    def info(self) -> Mapping[str, Any]: ...

class Trainer(ABC):
    @abstractmethod
    def train(self): ...
